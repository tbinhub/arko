function node(
    id: string,
    kind: ArchitectureNode["data"]["kind"],
    label: string,
    x: number,
    y: number,
    accent: ArchitectureNode["data"]["accent"],
    icon: string,
    description: string,
): ArchitectureNode {
    return {
        id,
        type: "architecture",
        position: { x, y },
        data: { kind, label, accent, icon, description },
    };
}

function edge(
    id: string,
    source: string,
    target: string,
    label = "",
    protocol = "HTTPS",
): ArchitectureEdge {
    return {
        id,
        source,
        target,
        type: "smoothstep",
        data: { label, protocol, animated: false },
    };
}

